"""Deterministic mock provider.

The generator is a pure function of (catalogue, date), so re-running a sync
produces identical history. That makes the demo reproducible and the ingestion
idempotency test meaningful.
"""

from __future__ import annotations

import math
import random
from datetime import date, datetime, timedelta, timezone

from app.connectors.base import (
    ConnectorDataset,
    ListingRecord,
    ObservationPoint,
    ProductCandidate,
    SupplierOfferRecord,
    SupplierRecord,
)
from app.connectors.catalog import MOCK_PRODUCTS, MockProduct
from app.services.normalise import keywords_from_name


def _rng(*parts: object) -> random.Random:
    return random.Random("|".join(str(p) for p in parts))


def _level(product: MockProduct, day: date, index: int, total_days: int) -> float:
    base = product.base_level
    archetype = product.archetype

    if archetype == "new":
        value = base + index * 0.35
    elif archetype == "rising":
        value = base * (1 + 0.0012 * index) + max(0, index - (total_days - 70)) * 0.30
    elif archetype == "emerging":
        value = base + max(0, index - (total_days - 80)) * 0.45
    elif archetype == "declining":
        value = base * (1 - 0.0010 * index) - max(0, index - (total_days - 70)) * 0.22
    elif archetype == "seasonal":
        peak = date(day.year, product.peak_month, 15).timetuple().tm_yday
        doy = day.timetuple().tm_yday
        value = base * (1 + 0.55 * math.cos(2 * math.pi * (doy - peak) / 365))
    else:
        value = base * (1 + 0.04 * math.sin(2 * math.pi * index / 45))

    weekday = 1 + 0.05 * math.sin(2 * math.pi * day.weekday() / 7)
    noise = _rng(product.slug, day.isoformat()).uniform(0.92, 1.08)
    return max(1.0, min(100.0, value * weekday * noise))


SUPPLIER_DEFS = [
    ("Shenzhen Brightline Trading", "CN", 4.6),
    ("Yiwu Harbour Supply", "CN", 4.3),
    ("Melbourne Fulfilment Co", "AU", 4.8),
]


def build_mock_dataset(
    as_of: date | None = None,
    product_limit: int = 48,
    history_days: int = 400,
) -> ConnectorDataset:
    as_of = as_of or date.today()
    dataset = ConnectorDataset()
    products = MOCK_PRODUCTS[: max(1, product_limit)]

    dataset.suppliers = [
        SupplierRecord(
            supplier_name=name,
            platform_key="mock",
            country=country,
            rating=rating,
            url=f"https://example.invalid/suppliers/{slug}",
        )
        for name, country, rating in SUPPLIER_DEFS
        for slug in [name.lower().replace(" ", "-")]
    ]

    for product in products:
        # "new" products are discovered inside the 30-day emerging window, so
        # their history must start within it too: 25 days is enough for the 7-day
        # growth comparison that the emerging rule requires. Discovery can
        # backfill earlier history, so "first seen" is five days ago even though
        # observations reach back 25 days.
        product_days = 25 if product.archetype == "new" else history_days
        start = as_of - timedelta(days=product_days)
        first_seen = as_of - timedelta(days=5) if product.archetype == "new" else start
        dataset.products.append(
            ProductCandidate(
                external_id=f"mock-{product.slug}",
                name=product.name,
                category_slug=product.category_slug,
                brand=product.brand,
                price=product.price,
                description=(
                    f"{product.name} by {product.brand}. Synthetic demo record, "
                    "generated by the mock connector and not a real market observation."
                ),
                keywords=keywords_from_name(product.name),
                is_synthetic=True,
                first_seen_at=datetime.combine(first_seen, datetime.min.time(), timezone.utc),
            )
        )

        level_today = 0.0
        for index in range(product_days + 1):
            day = start + timedelta(days=index)
            value = _level(product, day, index, product_days)
            level_today = value
            dataset.observations.append(
                ObservationPoint(
                    external_id=f"mock-{product.slug}",
                    observation_date=day,
                    metric_name="search_interest",
                    metric_value=round(value, 2),
                    unit="index_0_100",
                    confidence=0.9,
                    meta={"geo": "AU", "request_window": "400d", "synthetic": True},
                )
            )

        rng = _rng(product.slug, "market")
        review_velocity = 0.4 + (level_today / 100.0) * 6.0
        listing_count = int(max(5, (level_today**2) / 6.0 * rng.uniform(0.85, 1.15)))
        for offset in range(0, product_days + 1, 7):
            day = start + timedelta(days=offset)
            price = round(product.price * (1 + 0.03 * math.sin(offset / 30)), 2)
            dataset.observations.extend(
                [
                    ObservationPoint(
                        external_id=f"mock-{product.slug}",
                        observation_date=day,
                        metric_name="marketplace_listing_count",
                        metric_value=listing_count,
                        unit="count",
                        granularity="weekly",
                    ),
                    ObservationPoint(
                        external_id=f"mock-{product.slug}",
                        observation_date=day,
                        metric_name="marketplace_avg_price",
                        metric_value=price,
                        unit="aud",
                        granularity="weekly",
                        meta={"currency": "AUD"},
                    ),
                    ObservationPoint(
                        external_id=f"mock-{product.slug}",
                        observation_date=day,
                        metric_name="marketplace_review_velocity",
                        metric_value=round(review_velocity, 2),
                        unit="count",
                        granularity="weekly",
                    ),
                ]
            )

        for n in range(6):
            lrng = _rng(product.slug, "listing", n)
            dataset.listings.append(
                ListingRecord(
                    external_id=f"mock-{product.slug}",
                    marketplace="mock",
                    listing_id=f"mock-{product.slug}-{n}",
                    title=f"{product.name} (listing {n + 1})",
                    seller_name=lrng.choice(
                        ["Aussie Deals", "Urban Nest", "Bright Cart", "Coastal Living"]
                    ),
                    price=round(product.price * lrng.uniform(0.82, 1.18), 2),
                    rating=round(lrng.uniform(3.8, 5.0), 2),
                    review_count=lrng.randint(5, 4000),
                )
            )

        if rng.random() < 0.72:
            supplier = rng.choice(dataset.suppliers)
            dataset.offers.append(
                SupplierOfferRecord(
                    external_id=f"mock-{product.slug}",
                    supplier_name=supplier.supplier_name,
                    external_product_id=f"SP-{product.slug.upper()[:12]}-{rng.randint(100, 999)}",
                    product_cost=round(product.price * rng.uniform(0.22, 0.38), 2),
                    shipping_cost=round(rng.uniform(2.5, 6.5), 2),
                    minimum_order_quantity=rng.choice([1, 10, 50, 100]),
                    lead_time_days=rng.randint(7, 30),
                    availability=rng.choice(["in_stock", "in_stock", "in_stock", "low_stock"]),
                )
            )

    return dataset


def dataset_start_date(as_of: date | None = None, history_days: int = 400) -> datetime:
    as_of = as_of or date.today()
    return datetime.combine(as_of - timedelta(days=history_days), datetime.min.time(), timezone.utc)
